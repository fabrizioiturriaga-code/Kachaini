CREATE TABLE unidades_docente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docente_id BIGINT NOT NULL REFERENCES docentes(id) ON DELETE CASCADE,
    grado INTEGER NOT NULL CHECK (grado BETWEEN 1 AND 5),
    titulo VARCHAR(100) NOT NULL CHECK (length(trim(titulo)) > 0),
    creada TIMESTAMP WITH TIME ZONE NOT NULL,
    actualizada TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_unidades_docente_grado ON unidades_docente (grado, id);
CREATE INDEX ix_unidades_docente_docente ON unidades_docente (docente_id, id);

CREATE TABLE lecciones_docente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidad_id BIGINT NOT NULL REFERENCES unidades_docente(id) ON DELETE CASCADE,
    orden INTEGER NOT NULL CHECK (orden >= 1),
    titulo VARCHAR(100) NOT NULL CHECK (length(trim(titulo)) > 0),
    contenido VARCHAR(3000) NOT NULL CHECK (length(trim(contenido)) > 0),
    pregunta VARCHAR(300) NOT NULL CHECK (length(trim(pregunta)) > 0),
    opcion_a VARCHAR(200) NOT NULL CHECK (length(trim(opcion_a)) > 0),
    opcion_b VARCHAR(200) NOT NULL CHECK (length(trim(opcion_b)) > 0),
    opcion_c VARCHAR(200) NOT NULL CHECK (length(trim(opcion_c)) > 0),
    respuesta_correcta INTEGER NOT NULL CHECK (respuesta_correcta BETWEEN 0 AND 2),
    CONSTRAINT uk_lecciones_docente_orden UNIQUE (unidad_id, orden) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE lecciones_docente_completadas (
    estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    leccion_id BIGINT NOT NULL REFERENCES lecciones_docente(id) ON DELETE CASCADE,
    fecha TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (estudiante_id, leccion_id)
);
