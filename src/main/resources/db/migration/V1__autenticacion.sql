CREATE TABLE usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL,
 correo VARCHAR(254) NOT NULL,
 contrasena_hash VARCHAR(60) NOT NULL,
 fecha_registro TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT uk_usuarios_correo UNIQUE(correo),
 CONSTRAINT ck_correo_normalizado CHECK (correo = lower(trim(correo))),
 CONSTRAINT ck_hash CHECK (contrasena_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$')
);
CREATE TABLE estudiantes (
 id BIGINT PRIMARY KEY REFERENCES usuarios(id),
 grado INTEGER NOT NULL CHECK (grado BETWEEN 1 AND 5),
 seccion VARCHAR(1) NOT NULL CHECK (seccion IN ('A','B','C','D','E','F')),
 onboarding_completado BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE docentes (
 id BIGINT PRIMARY KEY REFERENCES usuarios(id),
 area VARCHAR(100) NOT NULL CHECK (length(trim(area)) > 0),
 autorizado BOOLEAN NOT NULL DEFAULT FALSE
);