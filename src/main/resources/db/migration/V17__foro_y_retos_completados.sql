ALTER TABLE notificaciones ADD COLUMN completada TIMESTAMP WITH TIME ZONE;

CREATE TABLE publicaciones_foro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grado INTEGER NOT NULL CHECK (grado BETWEEN 1 AND 5),
    seccion VARCHAR(1) NOT NULL CHECK (seccion IN ('A','B','C','D','E','F')),
    autor_id BIGINT REFERENCES estudiantes(id) ON DELETE CASCADE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('MENSAJE','RETO_SALON','RACHA')),
    texto VARCHAR(500) NOT NULL CHECK (length(trim(texto)) > 0),
    clave VARCHAR(100),
    creada TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_publicaciones_foro_clave UNIQUE (clave),
    CONSTRAINT ck_publicaciones_foro_autor CHECK ((tipo = 'MENSAJE') = (autor_id IS NOT NULL))
);

CREATE INDEX ix_publicaciones_foro_salon ON publicaciones_foro (grado, seccion, creada);