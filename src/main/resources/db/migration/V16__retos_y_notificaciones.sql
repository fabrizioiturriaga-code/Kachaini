CREATE TABLE retos_docente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docente_id BIGINT NOT NULL REFERENCES docentes(id) ON DELETE CASCADE,
    grado INTEGER NOT NULL CHECK (grado BETWEEN 1 AND 5),
    seccion VARCHAR(1) CHECK (seccion IN ('A','B','C','D','E','F')),
    titulo VARCHAR(100) NOT NULL CHECK (length(trim(titulo)) > 0),
    descripcion VARCHAR(1000) NOT NULL CHECK (length(trim(descripcion)) > 0),
    objetivos VARCHAR(1000) NOT NULL CHECK (length(trim(objetivos)) > 0),
    fecha_limite DATE NOT NULL,
    xp INTEGER NOT NULL CHECK (xp BETWEEN 0 AND 100),
    publicado TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_retos_docente_docente ON retos_docente (docente_id, publicado);

CREATE TABLE notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    reto_id BIGINT NOT NULL REFERENCES retos_docente(id) ON DELETE CASCADE,
    creada TIMESTAMP WITH TIME ZONE NOT NULL,
    leida TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_notificaciones_estudiante_reto UNIQUE (estudiante_id, reto_id)
);

CREATE INDEX ix_notificaciones_estudiante ON notificaciones (estudiante_id, creada);