
CREATE TABLE xp_ganada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_xp_ganada_estudiante_fecha ON xp_ganada (estudiante_id, fecha);

INSERT INTO xp_ganada (estudiante_id, cantidad, fecha)
SELECT estudiante_id, 20, fecha FROM lecciones_completadas;

