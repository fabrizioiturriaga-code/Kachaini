        CHECK (liga IN ('AMAUTA', 'PANACA', 'AUQUI', 'INCA'));

ALTER TABLE estudiantes ADD COLUMN liga_semana DATE;

CREATE TABLE cambios_liga (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    liga_anterior VARCHAR(20) NOT NULL,
    liga_nueva VARCHAR(20) NOT NULL,
    ascenso BOOLEAN NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE NOT NULL,
    notificado BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX ix_cambios_liga_estudiante ON cambios_liga (estudiante_id, notificado);
