CREATE TABLE practicas_realizadas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('LECTURA', 'ARRASTRE')),
    codigo VARCHAR(60) NOT NULL,
    aciertos INTEGER NOT NULL CHECK (aciertos >= 0),
    total INTEGER NOT NULL CHECK (total > 0 AND aciertos <= total),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_practicas_estudiante_fecha ON practicas_realizadas (estudiante_id, fecha);

CREATE TABLE recompensas_practica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('LECTURA', 'ARRASTRE')),
    codigo VARCHAR(60) NOT NULL,
    xp INTEGER NOT NULL CHECK (xp >= 0),
    coleccionable VARCHAR(40),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (estudiante_id, tipo, codigo),
    UNIQUE (estudiante_id, coleccionable)
);

ALTER TABLE intentos_leccion
