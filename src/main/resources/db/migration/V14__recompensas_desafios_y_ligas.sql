CREATE TABLE desafios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creador_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    companero_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    tipo VARCHAR(30) NOT NULL,
    estado VARCHAR(20) NOT NULL
        CHECK (estado IN ('PENDIENTE', 'ACTIVO', 'COMPLETADO', 'RECHAZADO')),
    creado TIMESTAMP WITH TIME ZONE NOT NULL,
    iniciado TIMESTAMP WITH TIME ZONE,
    completado TIMESTAMP WITH TIME ZONE,
    CHECK (creador_id <> companero_id)
);

CREATE INDEX ix_desafios_creador ON desafios (creador_id, estado);
CREATE INDEX ix_desafios_companero ON desafios (companero_id, estado);

