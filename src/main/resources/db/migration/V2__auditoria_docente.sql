CREATE TABLE docentes_autorizaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docente_id BIGINT NOT NULL,
    autorizado BOOLEAN NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    operador_bd TEXT NOT NULL DEFAULT CURRENT_USER
);

CREATE FUNCTION registrar_autorizacion_docente() RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO docentes_autorizaciones (docente_id, autorizado)
    VALUES (NEW.id, NEW.autorizado);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER auditar_autorizacion_docente
AFTER UPDATE OF autorizado ON docentes
FOR EACH ROW WHEN (OLD.autorizado IS DISTINCT FROM NEW.autorizado)
EXECUTE FUNCTION registrar_autorizacion_docente();
