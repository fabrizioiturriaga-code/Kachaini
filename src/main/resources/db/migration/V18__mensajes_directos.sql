CREATE TABLE mensajes_directos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docente_id BIGINT NOT NULL REFERENCES docentes(id) ON DELETE CASCADE,
    estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    enviado_por_docente BOOLEAN NOT NULL,
    texto VARCHAR(1000) NOT NULL CHECK (length(trim(texto)) > 0),
    enviado TIMESTAMP WITH TIME ZONE NOT NULL,
    leido TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_mensajes_directos_conversacion
    ON mensajes_directos (docente_id, estudiante_id, enviado);

CREATE INDEX ix_mensajes_directos_estudiante ON mensajes_directos (estudiante_id, enviado);
