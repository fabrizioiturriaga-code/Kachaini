CREATE TABLE intentos_leccion (
    estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    intento UUID NOT NULL,
    PRIMARY KEY (estudiante_id, intento)
);

CREATE TABLE entregas_desarrollo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    leccion VARCHAR(40) NOT NULL,
    texto VARCHAR(2000) NOT NULL,
    fecha_envio TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (estudiante_id, leccion)
);
